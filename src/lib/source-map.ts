export const componentName = (slug: string) => map[slug]?.[0];

export function sourceOf(slug: string) {
  const hit = map[slug];
  if (!hit) return { file: "src/components/docs/demos.tsx", module: null, importLine: "// Demo built from smaller parts; see src/components/docs/demos.tsx" };
  const [name, file] = hit;
  return { file: `packages/ui/src/${file}.tsx`, module: `@scopesky/ui/${file}`, importLine: `import { ${name} } from "@scopesky/ui/${file}";` };
}
