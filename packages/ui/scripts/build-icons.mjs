// Reads every icon in ../icons/*.svg and writes ../src/icon-data.ts.
// The SVG files are the source of truth: add or edit a file there, then run
// `npm run icons` (the build runs it for you). Plain Node, no dependencies.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "icons");
const files = readdirSync(dir).filter((f) => f.endsWith(".svg")).sort();

const icons = {};
for (const file of files) {
  const name = file.replace(/\.svg$/, "");
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) throw new Error(`Icon file names must be kebab-case: ${file}`);
  const svg = readFileSync(join(dir, file), "utf8");
  const body = (svg.match(/<g id="icon">([\s\S]*?)<\/g>/) ?? svg.match(/<svg[^>]*>([\s\S]*?)<\/svg>/))?.[1];
  if (!body) throw new Error(`Could not read shapes from ${file}`);
  const shapes = [...body.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g)].map(([, tag, attrs]) => {
    const a = {};
    // Attribute names can contain digits (x1, y2), so allow them after the first letter.
    for (const [, k, v] of attrs.matchAll(/([a-zA-Z][a-zA-Z0-9:-]*)="([^"]*)"/g)) a[k] = v;
    if (!Object.keys(a).length) throw new Error(`A <${tag}> in ${file} has no attributes`);
    return [tag, a];
  });
  if (!shapes.length) throw new Error(`No shapes found in ${file}`);
  icons[name] = shapes;
}

const rows = Object.entries(icons).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const out = `// Generated by scripts/build-icons.mjs from icons/*.svg. Do not edit by hand.

export type IconShape = readonly [tag: "path" | "circle" | "rect" | "line" | "polyline" | "polygon" | "ellipse", attrs: Readonly<Record<string, string>>];

export const iconData = {
${rows.join("\n")}
} as const satisfies Record<string, readonly IconShape[]>;

export type IconName = keyof typeof iconData;

export const iconNames = Object.keys(iconData) as IconName[];
`;
writeFileSync(join(root, "src", "icon-data.ts"), out);
console.log(`icons: wrote ${files.length} icons to src/icon-data.ts`);
